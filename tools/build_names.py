"""Merge checked name data (data/names/btn_*.json, read from Behind the Name pages) into static/name-btn.js.

Each name: meaning (English, as the source states), origin, variants by language, top = best popularity ranks
[region, year, rank] from official birth statistics as compiled by Behind the Name. Run after adding a batch:
    python3 tools/build_names.py
"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
merged = {}
for f in sorted((root / "data" / "names").glob("btn_*.json")):
    for k, v in json.loads(f.read_text(encoding="utf-8")).items():
        if k.startswith("_") or "error" in v:
            continue
        merged[k] = v
out = root / "static" / "name-btn.js"
out.write_text("/* generated by tools/build_names.py from data/names/btn_*.json (source: behindthename.com, checked 2026-11-25) */\nwindow.NADRI_BTN=" + json.dumps(merged, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
print(f"{len(merged)} names -> {out.relative_to(root)}")
